import uuid
from typing import Any, Literal

from pydantic import BaseModel, Field, field_validator

AnalyticalIntent = Literal[
    "dataset_summary",
    "descriptive_statistics",
    "group_by",
    "filtered_aggregation",
    "time_series",
    "ranking",
    "comparison",
    "distribution",
    "data_quality",
]

PlanAggregationMethod = Literal[
    "sum",
    "avg",
    "min",
    "max",
    "count",
    "distinct_count",
    "median",
]

PlanTimeGranularity = Literal[
    "daily",
    "weekly",
    "monthly",
    "quarterly",
    "yearly",
]

PlanSortDirection = Literal["asc", "desc"]


class PlanFilterCondition(BaseModel):
    column: str
    operator: Literal[
        "eq",
        "neq",
        "gt",
        "gte",
        "lt",
        "lte",
        "contains",
        "not_contains",
        "starts_with",
        "ends_with",
        "is_null",
        "is_not_null",
        "between",
    ]
    value: Any
    second_value: Any | None = None


class AnalyticalPlan(BaseModel):
    """
    Structured analytical plan generated by the AI parser.
    Strictly validated against schema metadata before passing to the execution engine.
    """

    intent: AnalyticalIntent
    metric_column: str | None = None
    aggregation: PlanAggregationMethod = "sum"
    group_by_columns: list[str] = Field(default_factory=list)
    filters: list[PlanFilterCondition] = Field(default_factory=list)
    date_column: str | None = None
    time_granularity: PlanTimeGranularity = "monthly"
    sort_direction: PlanSortDirection = "desc"
    limit: int = Field(default=20, ge=1, le=100)
    needs_clarification: bool = False
    clarification_message: str | None = None

    @field_validator("limit")
    @classmethod
    def cap_limit(cls, v: int) -> int:
        return max(1, min(v, 100))


class AIEvidenceItem(BaseModel):
    id: str
    title: str
    source_column: str
    calculation_type: str
    formula_or_query: str
    raw_result: Any
    formatted_result: str
    confidence: float = 1.0
    verified_by_engine: bool = True
    dataset_version_id: str | None = None
    row_count_analyzed: int
    execution_time_ms: int


class AIMetricCard(BaseModel):
    label: str
    value: str
    trend: str | None = None
    is_positive: bool | None = None


class AIChartData(BaseModel):
    type: Literal["bar", "line", "pie"]
    title: str
    labels: list[str]
    values: list[float]
    unit: str | None = None


class AITableData(BaseModel):
    headers: list[str]
    rows: list[list[Any]]


class ChatMessage(BaseModel):
    role: Literal["user", "assistant"]
    content: str = Field(..., min_length=1, max_length=2000)


class AIAskRequest(BaseModel):
    dataset_id: uuid.UUID
    version_id: uuid.UUID | None = None
    question: str = Field(..., min_length=2, max_length=1000)
    conversation_id: str | None = None
    conversation_history: list[ChatMessage] = Field(default_factory=list, max_length=10)


class AIAskResponse(BaseModel):
    direct_answer: str
    metrics: list[AIMetricCard] = Field(default_factory=list)
    chart_data: AIChartData | None = None
    table_data: AITableData | None = None
    interpretation: str
    evidence: list[AIEvidenceItem] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)
    suggested_follow_ups: list[str] = Field(default_factory=list)
    plan: AnalyticalPlan
    analysis_run_id: str | None = None
    dataset_version_id: str | None = None
    ai_status: Literal["operational", "disabled", "error"] = "operational"



class AIClarifyRequest(BaseModel):
    dataset_id: uuid.UUID
    version_id: uuid.UUID | None = None
    question: str
    original_plan: AnalyticalPlan
    user_clarification: str


class AIExplainRequest(BaseModel):
    dataset_id: uuid.UUID
    analysis_run_id: uuid.UUID
    audience: str = "Executive Board"


class AIExplainResponse(BaseModel):
    analysis_run_id: str
    explanation: str


class AIStatusResponse(BaseModel):
    ai_enabled: bool
    provider: str
    model: str
    operational: bool
    error: str | None = None



